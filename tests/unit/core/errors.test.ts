import { describe, expect, test, vi } from "vitest";
import {
	createAppError,
	isAppError,
	normalizeError,
	withCorrelationId,
} from "../../../src/core/errors";

describe("createAppError", () => {
	test("returns the documented shape", () => {
		expect(createAppError("network", "Try again", true)).toEqual({
			code: "network",
			message: "Try again",
			retryable: true,
		});
	});

	test("preserves empty strings and a false retryable flag", () => {
		expect(createAppError("", "", false)).toEqual({
			code: "",
			message: "",
			retryable: false,
		});
	});
});

describe("isAppError", () => {
	test("accepts values with the exact contract field types", () => {
		expect(isAppError(createAppError("code", "message", false))).toBe(true);
		expect(isAppError({ code: "", message: "", retryable: true })).toBe(true);
	});

	test.each([
		["null", null],
		["undefined", undefined],
		["number", 42],
		["string", "boom"],
		["empty object", {}],
		["message only", { message: "boom" }],
		["missing retryable", { code: "c", message: "m" }],
		["wrong retryable type", { code: "c", message: "m", retryable: "true" }],
		["wrong code type", { code: 1, message: "m", retryable: true }],
		["wrong message type", { code: "c", message: 1, retryable: true }],
		["native Error", new Error("boom")],
	])("rejects %s", (_label, value) => {
		expect(isAppError(value)).toBe(false);
	});

	test("ignores extra fields while keeping the structural check", () => {
		expect(
			isAppError({
				code: "c",
				message: "m",
				retryable: false,
				stack: "secret",
			}),
		).toBe(true);
	});
});

describe("normalizeError", () => {
	test("returns AppError values unchanged", () => {
		const error = createAppError("timeout", "Try again later", true);
		expect(normalizeError(error)).toBe(error);
	});

	test.each([
		["native Error with secret message", new Error("secret stack detail")],
		["string throw", "secret string"],
		["number throw", 500],
		["null", null],
		["undefined", undefined],
		["object with message", { message: "secret message" }],
		["object with stack", { stack: "secret stack", message: "secret message" }],
		["plain object", { reason: "secret reason" }],
	])("never leaks data from %s", (_label, value) => {
		const normalized = normalizeError(value);

		expect(normalized).toEqual({
			code: "unknown",
			message: expect.any(String),
			retryable: false,
		});
		expect(JSON.stringify(normalized)).not.toContain("secret");
		expect(JSON.stringify(normalized)).not.toContain("500");
	});

	test("uses one stable safe message for all non-AppError values", () => {
		const first = normalizeError(new Error("secret one"));
		const second = normalizeError({ message: "secret two" });

		expect(first.message).toBe(second.message);
		expect(first.message.length).toBeGreaterThan(0);
	});
});

describe("withCorrelationId", () => {
	test("returns the value generated by crypto.randomUUID", () => {
		const id = "00000000-0000-4000-8000-000000000000";
		const spy = vi.spyOn(globalThis.crypto, "randomUUID").mockReturnValue(id);

		try {
			expect(withCorrelationId()).toBe(id);
			expect(spy).toHaveBeenCalledOnce();
		} finally {
			spy.mockRestore();
		}
	});

	test("generates distinct ids on repeated calls", () => {
		const first = withCorrelationId();
		const second = withCorrelationId();

		expect(first).not.toBe(second);
		expect(first).toMatch(
			/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/,
		);
	});
});
